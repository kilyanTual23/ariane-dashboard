import type { ReactNode, SVGProps } from "react";

/**
 * Jeu d'icônes au trait, dessinées sur une grille 24 × 24 dans l'esprit de
 * Lucide. Embarquées ici plutôt qu'en dépendance : le déploiement ne relance
 * pas `npm install`, et une trentaine de tracés suffisent à l'application.
 */
export type IconProps = SVGProps<SVGSVGElement> & { size?: number | string };

function icon(name: string, children: ReactNode) {
  function Icon({ size = 16, strokeWidth = 1.75, className = "", ...rest }: IconProps) {
    return (
      <svg
        xmlns="http://www.w3.org/2000/svg"
        width={size}
        height={size}
        viewBox="0 0 24 24"
        fill="none"
        stroke="currentColor"
        strokeWidth={strokeWidth}
        strokeLinecap="round"
        strokeLinejoin="round"
        aria-hidden="true"
        focusable="false"
        className={`shrink-0 ${className}`}
        {...rest}
      >
        {children}
      </svg>
    );
  }
  Icon.displayName = `Icon${name}`;
  return Icon;
}

